// Package quickstart detects the web framework of a project from its on-disk
// markers and generates a tailored Heramba config — the "deploy in an afternoon"
// on-ramp: point it at your repo, get a .heramba.yml with the right decoy preset
// already chosen.
package quickstart

import (
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"
	"strings"
)

// Stack is a detected framework; "" means unknown.
type Stack struct {
	Name   string // matches a decoy preset name
	Reason string // the marker that identified it
}

// Detect inspects dir for framework markers and returns the best match. More
// specific frameworks (Next.js, Laravel) are checked before generic ones (Node).
func Detect(dir string) Stack {
	exists := func(rel string) bool {
		_, err := os.Stat(filepath.Join(dir, filepath.FromSlash(rel)))
		return err == nil
	}

	// Next.js: a next.config.* or "next" in package.json dependencies.
	if exists("next.config.js") || exists("next.config.mjs") || exists("next.config.ts") || pkgHasDep(dir, "next") {
		return Stack{"next", "Next.js config / dependency"}
	}
	// Laravel before generic PHP.
	if exists("artisan") || (exists("composer.json") && exists("app/Http")) {
		return Stack{"laravel", "Laravel artisan / app structure"}
	}
	if exists("wp-config.php") || exists("wp-config-sample.php") || exists("wp-content") {
		return Stack{"wordpress", "WordPress wp-config / wp-content"}
	}
	if exists("manage.py") {
		return Stack{"django", "Django manage.py"}
	}
	if exists("Gemfile") || exists("config.ru") {
		return Stack{"rails", "Ruby Gemfile / config.ru"}
	}
	if exists("pom.xml") || exists("build.gradle") || exists("build.gradle.kts") {
		return Stack{"spring", "Java pom.xml / build.gradle"}
	}
	// Generic Node last (Next.js already handled above).
	if exists("package.json") {
		return Stack{"node", "Node package.json"}
	}
	return Stack{"", "no known framework markers"}
}

// pkgHasDep reports whether package.json lists dep in (dev)dependencies.
func pkgHasDep(dir, dep string) bool {
	b, err := os.ReadFile(filepath.Join(dir, "package.json"))
	if err != nil {
		return false
	}
	var pkg struct {
		Dependencies    map[string]string `json:"dependencies"`
		DevDependencies map[string]string `json:"devDependencies"`
	}
	if json.Unmarshal(b, &pkg) != nil {
		return false
	}
	_, a := pkg.Dependencies[dep]
	_, d := pkg.DevDependencies[dep]
	return a || d
}

// GenerateConfig renders a commented .heramba.yml for the detected stack. An
// empty upstream yields honeypot-only; an empty stack omits the preset line.
func GenerateConfig(s Stack, upstream string) string {
	var b strings.Builder
	b.WriteString("# .heramba.yml — generated by `heramba quickstart`\n")
	if s.Name != "" {
		fmt.Fprintf(&b, "# Detected stack: %s (%s)\n", s.Name, s.Reason)
	}
	b.WriteString("mode: observe   # safe in prod; flip to protect when trusted\n")
	if upstream != "" {
		fmt.Fprintf(&b, "upstream: %q\n", upstream)
	} else {
		b.WriteString("# upstream: \"http://127.0.0.1:3000\"   # set your app's address\n")
	}
	b.WriteString("listen: \":8080\"\n")
	b.WriteString("admin_listen: \":9090\"   # health + /metrics\n")
	b.WriteString("decoys:\n  enabled: true\n")
	if s.Name != "" {
		fmt.Fprintf(&b, "  preset: %s   # framework-tailored lures\n", s.Name)
	}
	b.WriteString("alert:\n  format: jsonl\n  file: \"\"   # stdout; set a path to persist\n")
	return b.String()
}
